export const DEFAULT_THEME_ID: AppThemeId = 'system';

export function resolveAppTheme(
  themeId: AppThemeId,
  systemColorScheme: ColorScheme,
): AppTheme {
  return themeId === 'system'
    ? APP_THEMES[systemColorScheme === 'dark' ? 'midnight' : 'sunrise']
    : APP_THEMES[themeId];
}
