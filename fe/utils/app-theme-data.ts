export type ColorScheme = 'light' | 'dark';

export type ThemeColors = {
  text: string;
  background: string;
  tint: string;
  icon: string;
  tabIconDefault: string;
  tabIconSelected: string;
  surface: string;
  surfaceRaised: string;
  border: string;
  subtleBackground: string;
  subtleBorder: string;
  onTint: string;
};

